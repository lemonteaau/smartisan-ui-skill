"""Generate assets/flutter/smartisan_icons.dart from assets/icons-sprite.svg.

Run from the repo root:  python3 tools/gen_dart_icons.py
Only the monochrome sprite symbols (si-*, plus si-c-check) are converted; the multi-colour
ones (red check, delete, radio, clear, unselected) are drawn by widgets in smartisan_widgets.dart.
Path data in the sprite only uses absolute M L H V C Z, which is all this converter handles.
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
sprite = (root / "assets" / "icons-sprite.svg").read_text(encoding="utf-8")
out = root / "assets" / "flutter" / "smartisan_icons.dart"


def num(x):
    v = float(x)
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def path_to_dart(d):
    toks = re.findall(r"[MLHVCZmlhvcz]|-?\d*\.?\d+(?:e-?\d+)?", d)
    i, cmd, cx, cy, sx, sy = 0, None, 0.0, 0.0, 0.0, 0.0
    ops = []
    while i < len(toks):
        t = toks[i]
        if re.fullmatch(r"[A-Za-z]", t):
            cmd = t
            i += 1
            if cmd in "Zz":
                ops.append("..close()")
                cx, cy = sx, sy
            continue
        if cmd != cmd.upper():
            raise ValueError(f"relative command {cmd} not supported")
        if cmd == "M":
            cx, cy = float(toks[i]), float(toks[i + 1]); i += 2
            sx, sy = cx, cy
            ops.append(f"..moveTo({num(cx)}, {num(cy)})")
            cmd = "L"  # implicit lineto after moveto
        elif cmd == "L":
            cx, cy = float(toks[i]), float(toks[i + 1]); i += 2
            ops.append(f"..lineTo({num(cx)}, {num(cy)})")
        elif cmd == "H":
            cx = float(toks[i]); i += 1
            ops.append(f"..lineTo({num(cx)}, {num(cy)})")
        elif cmd == "V":
            cy = float(toks[i]); i += 1
            ops.append(f"..lineTo({num(cx)}, {num(cy)})")
        elif cmd == "C":
            a = [float(v) for v in toks[i:i + 6]]; i += 6
            cx, cy = a[4], a[5]
            ops.append("..cubicTo(" + ", ".join(num(v) for v in a) + ")")
        else:
            raise ValueError(f"unsupported command {cmd}")
    return "Path()" + "".join(ops)


def attr(tag, name, default=None):
    m = re.search(rf'\b{name}="([^"]*)"', tag)
    return m.group(1) if m else default


icons = []
for m in re.finditer(r'<symbol id="si-([^"]+)" viewBox="([^"]+)"[^>]*>(.*?)</symbol>', sprite, re.S):
    name, vb, body = m.group(1), m.group(2), m.group(3)
    if name.startswith("c-") and name != "c-check":
        continue
    dart_name = re.sub(r"[-_](\w)", lambda x: x.group(1).upper(), name.replace("c-", ""))
    parts = []
    for p in re.finditer(r"<path\b[^>]*/>", body):
        tag = p.group(0)
        d = attr(tag, "d")
        if not d:
            continue
        stroke = attr(tag, "stroke")
        fill = attr(tag, "fill")
        is_stroke = stroke not in (None, "none") and fill in (None, "none")
        both = stroke not in (None, "none") and fill not in (None, "none")
        sw = attr(tag, "stroke-width", "1")
        cap = {"round": "StrokeCap.round", "square": "StrokeCap.square"}.get(attr(tag, "stroke-linecap"), "StrokeCap.butt")
        join = {"round": "StrokeJoin.round", "bevel": "StrokeJoin.bevel"}.get(attr(tag, "stroke-linejoin"), "StrokeJoin.miter")
        even = attr(tag, "fill-rule") == "evenodd"
        style = "SIconPaint.fillAndStroke" if both else ("SIconPaint.stroke" if is_stroke else "SIconPaint.fill")
        parts.append(
            f"      SIconPart({path_to_dart(d)}, paint: {style}, strokeWidth: {num(sw)}, cap: {cap}, join: {join}, evenOdd: {str(even).lower()}),"
        )
    x, y, w, h = (num(v) for v in vb.split())
    icons.append((dart_name, name, x, y, w, h, parts))

lines = [
    "// GENERATED by tools/gen_dart_icons.py from assets/icons-sprite.svg — do not edit by hand.",
    "// Icons from \"Smartisan OS UI Kit (Unofficial)\" by Paix Chan, CC BY 4.0.",
    "// Usage:  SIcon(SIcons.back, size: 20)   — colour defaults to SColors.icon; pass color: to tint.",
    "",
    "import 'package:flutter/widgets.dart';",
    "",
    "enum SIconPaint { fill, stroke, fillAndStroke }",
    "",
    "class SIconPart {",
    "  const SIconPart(this.path, {this.paint = SIconPaint.fill, this.strokeWidth = 1, this.cap = StrokeCap.butt, this.join = StrokeJoin.miter, this.evenOdd = false});",
    "  final Path path;",
    "  final SIconPaint paint;",
    "  final double strokeWidth;",
    "  final StrokeCap cap;",
    "  final StrokeJoin join;",
    "  final bool evenOdd;",
    "}",
    "",
    "/// Vector icon data in its original viewBox.",
    "class SIconData {",
    "  const SIconData(this.name, this.viewBox, this.parts);",
    "  final String name;",
    "  final Rect viewBox;",
    "  final List<SIconPart> parts;",
    "}",
    "",
    "/// All monochrome icons of the kit. Multi-colour ones (red check, delete, radio, clear, unselected)",
    "/// are widgets in smartisan_widgets.dart.",
    "class SIcons {",
    "  SIcons._();",
]
for dart_name, name, x, y, w, h, parts in icons:
    lines.append(f"  /// si-{name}")
    lines.append(f"  static final SIconData {dart_name} = SIconData('{name}', const Rect.fromLTWH({x}, {y}, {w}, {h}), [")
    lines.extend(parts)
    lines.append("  ]);")
lines.append("")
lines.append("  static final Map<String, SIconData> all = {")
for dart_name, name, *_ in icons:
    lines.append(f"    '{name}': {dart_name},")
lines.append("  };")
lines.append("}")
lines.append("")

out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {out.relative_to(root)} ({len(icons)} icons)")
